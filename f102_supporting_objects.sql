    p_classification_confidence := json_number_or_null(l_result, 'c');
    p_brand_name := json_string_or_null(l_result, 'b');
    p_class_type := json_string_or_null(l_result, 't');
    p_abv := json_number_or_null(l_result, 'a');
    p_net_contents := json_string_or_null(l_result, 'n');
    p_producer := json_string_or_null(l_result, 'p');
    p_country := json_string_or_null(l_result, 'o');
    p_warning_present := json_boolean_yn_or_null(l_result, 'wp');
    p_warning := json_string_or_null(l_result, 'w');
    p_warning_all_caps := json_boolean_yn_or_null(l_result, 'u');
    p_warning_bold := json_boolean_yn_or_null(l_result, 'v');
    p_warning_legible := json_boolean_yn_or_null(l_result, 'z');
    p_confidence := json_number_or_null(l_result, 'q');

    if p_is_alcohol_label = 'Y' then
      p_raw_text := to_clob(trim(
        beverage_label(p_beverage_type) || chr(10) ||
        p_brand_name || chr(10) || p_class_type || chr(10) ||
        case when p_abv is not null then to_char(p_abv, 'FM990D999', 'NLS_NUMERIC_CHARACTERS=''.,''') || '% Alc./Vol.' end || chr(10) ||
        p_net_contents || chr(10) || p_producer || chr(10) || p_country || chr(10) || p_warning
      ));
    else
      p_raw_text := to_clob(trim(p_document_type || case when p_classification_reason is not null then ': ' || p_classification_reason end));
    end if;
    if p_classification_confidence is not null then p_classification_confidence := greatest(0, least(1, p_classification_confidence)); end if;
    if p_confidence is not null then p_confidence := greatest(0, least(1, p_confidence)); end if;

    if dbms_lob.istemporary(l_base64) = 1 then dbms_lob.freetemporary(l_base64); end if;
    if dbms_lob.istemporary(l_request) = 1 then dbms_lob.freetemporary(l_request); end if;
  exception
    when others then
      if l_base64 is not null and dbms_lob.istemporary(l_base64) = 1 then dbms_lob.freetemporary(l_base64); end if;
      if l_request is not null and dbms_lob.istemporary(l_request) = 1 then dbms_lob.freetemporary(l_request); end if;
      raise;
  end openai_extract;

  function file_basename(p_path in varchar2) return varchar2 is
    l_path varchar2(4000) := replace(p_path, chr(92), '/');
  begin
    return regexp_substr(l_path, '[^/]+$');
  end file_basename;

  function mime_from_name(p_file_name in varchar2) return varchar2 is
    l_ext varchar2(50) := lower(substr(p_file_name, instr(p_file_name, '.', -1) + 1));
  begin
    return case l_ext
      when 'jpg' then 'image/jpeg'
      when 'jpeg' then 'image/jpeg'
      when 'png' then 'image/png'
      when 'webp' then 'image/webp'
      when 'gif' then 'image/gif'
      else 'application/octet-stream'
    end;
  end mime_from_name;

  function effective_mime(
    p_file_name in varchar2,
    p_mime_type in varchar2
  ) return varchar2 is
    l_mime varchar2(255) := lower(regexp_substr(trim(p_mime_type), '^[^;]+'));
  begin
    if l_mime = 'image/jpg' then
      return 'image/jpeg';
    elsif l_mime in ('image/jpeg', 'image/png', 'image/webp', 'image/gif') then
      return l_mime;
    else
      return mime_from_name(p_file_name);
    end if;
  end effective_mime;

  function normalize_header(p_value in varchar2) return varchar2 is
    l_value varchar2(4000);
  begin
    l_value := lower(trim(replace(p_value, unistr('\FEFF'), '')));
    l_value := regexp_replace(l_value, '[^a-z0-9]+', '_');
    return regexp_replace(l_value, '^_+|_+$', '');
  end normalize_header;

  procedure validate_input(
    p_file_name              in varchar2,
    p_mime_type              in varchar2,
    p_image_blob             in blob,
    p_application_ref        in varchar2,
    p_beverage_type          in varchar2,
    p_abv_required           in char,
    p_expected_brand_name    in varchar2,
    p_expected_class_type    in varchar2,
    p_expected_abv           in number,
    p_expected_net_contents  in varchar2,
    p_expected_producer      in varchar2,
    p_is_demo                in boolean
  ) is
    l_max_bytes       number := safe_number(get_config('MAX_FILE_BYTES', '10485760'));
    l_mime            varchar2(255) := lower(trim(p_mime_type));
    l_beverage_type   varchar2(30) := normalize_beverage_type(p_beverage_type);
    l_abv_required    char(1) := normalize_yes_no(p_abv_required, 'Y');
  begin
    if trim(p_application_ref) is null then
      raise_application_error(-20001, 'Application reference is required.');
    elsif l_beverage_type is null or l_beverage_type not in ('DISTILLED_SPIRITS', 'WINE', 'BEER') then
      raise_application_error(-20012, 'Beverage category must be DISTILLED_SPIRITS, WINE, or BEER.');
    elsif l_beverage_type = 'DISTILLED_SPIRITS' and l_abv_required <> 'Y' then
      raise_application_error(-20013, 'Alcohol content must be marked required for the distilled-spirits prototype workflow.');
    elsif trim(p_expected_brand_name) is null or normalize_loose(p_expected_brand_name) is null then
      raise_application_error(-20002, 'Expected brand name is required and must contain letters or numbers.');
    elsif trim(p_expected_class_type) is null or normalize_loose(p_expected_class_type) is null then
      raise_application_error(-20003, 'Expected class/type is required and must contain letters or numbers.');
    elsif l_abv_required = 'Y' and (p_expected_abv is null or p_expected_abv < 0 or p_expected_abv > 100) then
      raise_application_error(-20004, 'Expected ABV must be between 0 and 100 when alcohol content is required.');
    elsif trim(p_expected_net_contents) is null or net_to_ml(p_expected_net_contents) is null then
      raise_application_error(-20005, 'Expected net contents must include a supported number and unit.');
    elsif trim(p_expected_producer) is null or normalize_loose(p_expected_producer) is null then
      raise_application_error(-20006, 'Expected bottler/producer is required and must contain letters or numbers.');
    end if;

    if p_image_blob is null then
      if not p_is_demo then raise_application_error(-20007, 'A label image is required for live verification.'); end if;
    else
      if trim(p_file_name) is null then
        raise_application_error(-20007, 'The uploaded image file name is missing.');
      elsif dbms_lob.getlength(p_image_blob) > coalesce(l_max_bytes, 10485760) then
        raise_application_error(-20008, 'The image exceeds the configured size limit.');
      elsif l_mime not in ('image/jpeg', 'image/png', 'image/webp', 'image/gif') then
        raise_application_error(-20009, 'Upload a JPEG, PNG, WEBP, or GIF image.');
      end if;
    end if;
  end validate_input;

  procedure verify_label(
    p_file_name              in varchar2,
    p_mime_type              in varchar2,
    p_image_blob             in blob,
    p_application_ref        in varchar2,
    p_expected_brand_name    in varchar2,
    p_expected_class_type    in varchar2,
    p_expected_abv           in number,
    p_expected_net_contents  in varchar2,
    p_expected_producer      in varchar2,
    p_beverage_type          in varchar2 default 'DISTILLED_SPIRITS',
    p_abv_required           in char default 'Y',
    p_expected_country       in varchar2 default null,
    p_demo_profile           in varchar2 default null,
    p_batch_id               in number default null,
    p_verification_id        out number
  ) is
    l_start                      number := dbms_utility.get_time;
    l_provider                   varchar2(30) := upper(get_config('PROVIDER', 'DEMO'));
    l_profile                    varchar2(30) := upper(trim(p_demo_profile));
    l_is_demo                    boolean;
    l_expected_beverage_type     varchar2(30) := normalize_beverage_type(p_beverage_type);
    l_abv_required               char(1) := normalize_yes_no(p_abv_required, 'Y');
    l_document_type              varchar2(500);
    l_is_alcohol_label           char(1);
    l_classification_reason      varchar2(4000);
    l_classification_confidence  number;
    l_beverage_type              varchar2(30);
    l_brand_name                 varchar2(500);
    l_class_type                 varchar2(1000);
    l_abv                        number;
    l_net_contents               varchar2(200);
    l_producer                   varchar2(1000);
    l_country                    varchar2(500);
    l_warning                    varchar2(4000);
    l_warning_present            char(1);
    l_warning_all_caps           char(1);
    l_warning_bold               char(1);
    l_warning_legible            char(1);
    l_raw_text                   clob;
    l_confidence                 number;
    l_http_status                number;
    l_provider_response          clob;
    l_overall_status             varchar2(20);
    l_elapsed_ms                 number;
    l_error_message              varchar2(4000);
    l_app_user                   varchar2(255) := app_user;
    l_effective_mime             varchar2(255) := effective_mime(p_file_name, p_mime_type);
    l_daily_limit                number := safe_number(get_config('LIVE_DAILY_LIMIT', '100'));
    l_hourly_limit               number := safe_number(get_config('LIVE_HOURLY_LIMIT', '30'));
    l_usage_count                number;
  begin
    if l_profile is not null then l_provider := 'DEMO'; end if;
    if l_provider = 'DEMO' and l_profile is null then
      raise_application_error(-20011, 'Live image analysis is not configured. Select a Demo mode or configure the OpenAI provider and APEX Web Credential.');
    end if;
    l_is_demo := (l_provider = 'DEMO');

    validate_input(p_file_name, l_effective_mime, p_image_blob, p_application_ref,
                   l_expected_beverage_type, l_abv_required,
                   p_expected_brand_name, p_expected_class_type, p_expected_abv,
                   p_expected_net_contents, p_expected_producer, l_is_demo);

    if l_provider = 'OPENAI' then
      if coalesce(l_hourly_limit, 0) > 0 then
        select count(*) into l_usage_count from alv_verifications
         where provider = 'OPENAI' and created_at >= systimestamp - numtodsinterval(1, 'HOUR');
        if l_usage_count >= l_hourly_limit then raise_application_error(-20014, 'The public live-test hourly limit has been reached. Try again later or use Demo scenarios.'); end if;
      end if;
      if coalesce(l_daily_limit, 0) > 0 then
        select count(*) into l_usage_count from alv_verifications
         where provider = 'OPENAI' and created_at >= systimestamp - numtodsinterval(24, 'HOUR');
        if l_usage_count >= l_daily_limit then raise_application_error(-20015, 'The public live-test daily limit has been reached. Try again later or use Demo scenarios.'); end if;
      end if;
    end if;

    insert into alv_verifications (
      public_token, batch_id, application_ref, file_name, mime_type, image_blob,
      beverage_type, abv_required,
      expected_brand_name, expected_class_type, expected_abv, expected_net_contents,
      expected_producer, expected_country, provider, demo_profile, overall_status, created_by
    ) values (
      lower(rawtohex(sys_guid())), p_batch_id, trim(p_application_ref), p_file_name,
      l_effective_mime, p_image_blob, l_expected_beverage_type, l_abv_required,
      trim(p_expected_brand_name), trim(p_expected_class_type),
      case when l_abv_required = 'Y' then p_expected_abv else null end,
      trim(p_expected_net_contents), trim(p_expected_producer), trim(p_expected_country),
      l_provider, l_profile, 'PROCESSING', l_app_user
    ) returning id into p_verification_id;

    begin
      if l_provider = 'DEMO' then
        demo_extract(
          l_profile, l_expected_beverage_type, l_abv_required,
          p_expected_brand_name, p_expected_class_type, p_expected_abv,
          p_expected_net_contents, p_expected_producer, p_expected_country,
          l_document_type, l_is_alcohol_label, l_classification_reason,
          l_classification_confidence, l_beverage_type,
          l_brand_name, l_class_type, l_abv, l_net_contents, l_producer, l_country,
          l_warning, l_warning_present, l_warning_all_caps, l_warning_bold,
          l_warning_legible, l_raw_text, l_confidence
        );
      elsif l_provider = 'OPENAI' then
        openai_extract(
          l_effective_mime, p_image_blob,
          l_document_type, l_is_alcohol_label, l_classification_reason,
          l_classification_confidence, l_beverage_type,
          l_brand_name, l_class_type, l_abv, l_net_contents, l_producer, l_country,
          l_warning, l_warning_present, l_warning_all_caps, l_warning_bold,
          l_warning_legible, l_raw_text, l_confidence, l_http_status, l_provider_response
        );
      else
        raise_application_error(-20010, 'Unsupported provider: ' || l_provider);
      end if;

      build_results(
        p_verification_id, l_document_type, l_is_alcohol_label,
        l_classification_reason, l_classification_confidence,
        l_expected_beverage_type, l_abv_required, l_beverage_type,
        p_expected_brand_name, p_expected_class_type, p_expected_abv,
        p_expected_net_contents, p_expected_producer, p_expected_country,
        l_brand_name, l_class_type, l_abv, l_net_contents, l_producer, l_country,
        l_warning, l_warning_present, l_warning_all_caps, l_warning_bold,
        l_warning_legible, l_confidence, l_overall_status
      );

      l_elapsed_ms := round((dbms_utility.get_time - l_start) * 10);
      update alv_verifications
         set extracted_beverage_type = l_beverage_type,
             extracted_brand_name = l_brand_name,
             extracted_class_type = l_class_type,
             extracted_abv = l_abv,
             extracted_net_contents = l_net_contents,
             extracted_producer = l_producer,
             extracted_country = l_country,
             extracted_warning = l_warning,
             warning_present = l_warning_present,
             warning_heading_all_caps = l_warning_all_caps,
             warning_heading_bold = l_warning_bold,
             warning_legible = l_warning_legible,
             extracted_text = l_raw_text,
             provider_response = l_provider_response,
             overall_status = l_overall_status,
             confidence = l_confidence,
             processing_ms = l_elapsed_ms,
             http_status = l_http_status,
             error_message = null
       where id = p_verification_id;
    exception
      when others then
        l_error_message := substr(sqlerrm, 1, 4000);
        l_elapsed_ms := round((dbms_utility.get_time - l_start) * 10);
        delete from alv_verification_fields where verification_id = p_verification_id;
        add_result(p_verification_id, 10, 'PROVIDER_ERROR', 'Extraction service',
                   'Successful extraction', 'Error', 'REVIEW', null, l_error_message);
        update alv_verifications
           set provider_response = l_provider_response,
               overall_status = 'REVIEW', processing_ms = l_elapsed_ms,
               http_status = l_http_status, error_message = l_error_message
         where id = p_verification_id;
    end;
  end verify_label;

