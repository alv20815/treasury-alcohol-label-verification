create or replace package body alv_verification_pkg as
  c_warning constant varchar2(4000) :=
    'GOVERNMENT WARNING: (1) According to the Surgeon General, women should not drink alcoholic beverages during pregnancy because of the risk of birth defects. (2) Consumption of alcoholic beverages impairs your ability to drive a car or operate machinery, and may cause health problems.';

  function app_user return varchar2 is
  begin
    return substr(
      coalesce(
        sys_context('APEX$SESSION', 'APP_USER'),
        sys_context('USERENV', 'SESSION_USER')
      ),
      1,
      255
    );
  end app_user;

  function get_config(
    p_key      in varchar2,
    p_default  in varchar2 default null
  ) return varchar2 is
    l_value alv_config.config_value%type;
  begin
    select config_value
      into l_value
      from alv_config
     where config_key = upper(trim(p_key));

    return coalesce(l_value, p_default);
  exception
    when no_data_found then
      return p_default;
  end get_config;

  procedure set_config(
    p_key          in varchar2,
    p_value        in varchar2,
    p_description  in varchar2 default null
  ) is
    l_app_user varchar2(255) := app_user;
  begin
    merge into alv_config d
    using (
      select upper(trim(p_key)) as config_key,
             p_value as config_value,
             p_description as description
        from dual
    ) s
       on (d.config_key = s.config_key)
     when matched then update set
       d.config_value = s.config_value,
       d.description = coalesce(s.description, d.description),
       d.updated_at = systimestamp,
       d.updated_by = l_app_user
     when not matched then insert
       (config_key, config_value, description, updated_at, updated_by)
       values
       (s.config_key, s.config_value, s.description, systimestamp, l_app_user);
  end set_config;

  function government_warning return varchar2 is
  begin
    return c_warning;
  end government_warning;

  function normalize_whitespace(p_value in varchar2) return varchar2 is
  begin
    return trim(regexp_replace(p_value, '[[:space:]]+', ' '));
  end normalize_whitespace;

  function normalize_loose(p_value in varchar2) return varchar2 is
  begin
    return regexp_replace(lower(coalesce(p_value, '')), '[^[:alnum:]]', '');
  end normalize_loose;

  function safe_number(p_value in varchar2) return number is
    l_text varchar2(4000);
    l_num  varchar2(4000);
  begin
    l_text := trim(p_value);

    -- Treat a comma as a thousands separator only for forms such as 1,000.
    -- Otherwise, accept it as a decimal separator (for example 0,75).
    if instr(l_text, '.') = 0
       and regexp_like(l_text, '(^|[^0-9])[1-9][0-9]{0,2}(,[0-9]{3})+([^0-9]|$)') then
      l_text := replace(l_text, ',', '');
    else
      l_text := replace(l_text, ',', '.');
    end if;

    l_num := regexp_substr(l_text, '([0-9]+([.][0-9]+)?|[.][0-9]+)');

    if l_num is null then
      return null;
    elsif substr(l_num, 1, 1) = '.' then
      l_num := '0' || l_num;
    end if;

    if instr(l_num, '.') > 0 then
      return to_number(
        l_num,
        '99999999999999999999D99999999999999999999',
        'NLS_NUMERIC_CHARACTERS=''.,'''
      );
    else
      return to_number(
        l_num,
        '99999999999999999999',
        'NLS_NUMERIC_CHARACTERS=''.,'''
      );
    end if;
  exception
    when others then
      return null;
  end safe_number;

  function net_to_ml(p_value in varchar2) return number is
    l_text varchar2(4000) := lower(coalesce(p_value, ''));
    l_pair varchar2(4000);
    l_num  number;
  begin
    -- Use the first complete number/unit pair. This avoids treating the second
    -- unit in a dual declaration such as "1 L (33.8 fl oz)" as the primary one.
    l_pair := regexp_substr(
      l_text,
      '([0-9]+([.,][0-9]+)?|[.,][0-9]+)[[:space:]]*(fl[[:space:].]*oz|fluid[[:space:]]*ounces?|ml|milliliters?|millilitres?|cl|centiliters?|centilitres?|l|liters?|litres?)',
      1,
      1,
      'i'
    );
    l_num := safe_number(l_pair);

    if l_pair is null or l_num is null then
      return null;
    elsif regexp_like(l_pair, 'fl[[:space:].]*oz|fluid[[:space:]]*ounces?', 'i') then
      return l_num * 29.5735295625;
    elsif regexp_like(l_pair, '(^|[^a-z])(cl|centiliters?|centilitres?)', 'i') then
      return l_num * 10;
    elsif regexp_like(l_pair, '(^|[^a-z])(ml|milliliters?|millilitres?)', 'i') then
      return l_num;
    elsif regexp_like(l_pair, '(^|[^a-z])(l|liters?|litres?)', 'i') then
      return l_num * 1000;
    else
      return null;
    end if;
  end net_to_ml;

  function bool_to_yn(p_value in boolean) return char is
  begin
    if p_value is null then
      return null;
    elsif p_value then
      return 'Y';
    else
      return 'N';
    end if;
  end bool_to_yn;

  procedure add_result(
    p_verification_id  in number,
    p_sequence         in number,
    p_code             in varchar2,
    p_label            in varchar2,
    p_expected         in varchar2,
    p_extracted        in varchar2,
    p_status           in varchar2,
    p_confidence       in number,
    p_detail           in varchar2
  ) is
  begin
    insert into alv_verification_fields (
      verification_id,
      display_sequence,
      field_code,
      field_label,
      expected_value,
      extracted_value,
      match_status,
      confidence,
      detail
    ) values (
      p_verification_id,
      p_sequence,
      p_code,
      p_label,
      substr(p_expected, 1, 4000),
      substr(p_extracted, 1, 4000),
      p_status,
      p_confidence,
      substr(p_detail, 1, 4000)
    );
  end add_result;

  procedure build_results(
    p_verification_id            in number,
    p_expected_brand_name        in varchar2,
    p_expected_class_type        in varchar2,
    p_expected_abv               in number,
    p_expected_net_contents      in varchar2,
    p_expected_producer          in varchar2,
    p_expected_country           in varchar2,
    p_extracted_brand_name       in varchar2,
    p_extracted_class_type       in varchar2,
    p_extracted_abv              in number,
    p_extracted_net_contents     in varchar2,
    p_extracted_producer         in varchar2,
    p_extracted_country          in varchar2,
    p_extracted_warning          in varchar2,
    p_warning_heading_all_caps   in char,
    p_warning_heading_bold       in char,
    p_confidence                 in number,
    p_overall_status             out varchar2
  ) is
    l_status             varchar2(30);
    l_detail             varchar2(4000);
    l_expected_ml        number;
    l_extracted_ml       number;
    l_min_confidence     number := safe_number(get_config('MIN_CONFIDENCE', '0.75'));
    l_abv_tolerance      number := safe_number(get_config('ABV_TOLERANCE', '0.05'));
    l_net_tolerance      number := safe_number(get_config('NET_TOLERANCE_ML', '2'));
    l_fail_count         number;
    l_review_count       number;
    l_expected_loose     varchar2(4000);
    l_extracted_loose    varchar2(4000);
    l_length_ratio       number;
  begin
    delete from alv_verification_fields
     where verification_id = p_verification_id;

    if p_extracted_brand_name is null then
      l_status := 'MISSING';
      l_detail := 'No brand name could be read from the label.';
    elsif normalize_loose(p_expected_brand_name) = normalize_loose(p_extracted_brand_name) then
      l_status := 'MATCH';
      l_detail := 'Case, spacing, and punctuation differences are intentionally ignored.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The normalized brand names differ.';
    end if;
    add_result(p_verification_id, 10, 'BRAND_NAME', 'Brand name',
               p_expected_brand_name, p_extracted_brand_name,
               l_status, p_confidence, l_detail);

    if p_extracted_class_type is null then
      l_status := 'MISSING';
      l_detail := 'No class/type designation could be read from the label.';
    elsif normalize_loose(p_expected_class_type) = normalize_loose(p_extracted_class_type) then
      l_status := 'MATCH';
      l_detail := 'Case, spacing, and punctuation differences are ignored.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The normalized class/type designations differ.';
    end if;
    add_result(p_verification_id, 20, 'CLASS_TYPE', 'Class / type',
               p_expected_class_type, p_extracted_class_type,
               l_status, p_confidence, l_detail);

    if p_extracted_abv is null then
      l_status := 'MISSING';
      l_detail := 'No ABV percentage could be read from the label.';
    elsif abs(p_expected_abv - p_extracted_abv) <= coalesce(l_abv_tolerance, 0.05) then
      l_status := 'MATCH';
      l_detail := 'Compared numerically using the configured ABV tolerance.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The extracted ABV differs from the application value.';
    end if;
    add_result(p_verification_id, 30, 'ABV', 'Alcohol by volume',
               to_char(p_expected_abv, 'FM990D999', 'NLS_NUMERIC_CHARACTERS=''.,''') || '%',
               case when p_extracted_abv is not null
                    then to_char(p_extracted_abv, 'FM990D999', 'NLS_NUMERIC_CHARACTERS=''.,''') || '%'
               end,
               l_status, p_confidence, l_detail);

    l_expected_ml := net_to_ml(p_expected_net_contents);
    l_extracted_ml := net_to_ml(p_extracted_net_contents);
    if p_extracted_net_contents is null then
      l_status := 'MISSING';
      l_detail := 'No net contents could be read from the label.';
    elsif l_expected_ml is null or l_extracted_ml is null then
      l_status := 'REVIEW';
      l_detail := 'The value was present, but its number or unit could not be normalized.';
    elsif abs(l_expected_ml - l_extracted_ml) <= coalesce(l_net_tolerance, 2) then
      l_status := 'MATCH';
      l_detail := 'Values were converted to milliliters before comparison.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The normalized net contents differ.';
    end if;
    add_result(p_verification_id, 40, 'NET_CONTENTS', 'Net contents',
               p_expected_net_contents, p_extracted_net_contents,
               l_status, p_confidence, l_detail);

    if p_expected_producer is null then
      l_status := 'NOT_APPLICABLE';
      l_detail := 'No producer value was supplied in the application data.';
    elsif p_extracted_producer is null then
      l_status := 'MISSING';
      l_detail := 'No bottler/producer name and address could be read.';
    else
      l_expected_loose := normalize_loose(p_expected_producer);
      l_extracted_loose := normalize_loose(p_extracted_producer);
      if l_extracted_loose is null then
        l_status := 'MISSING';
        l_detail := 'The extracted producer/address contains no usable text.';
      else
        l_length_ratio := least(length(l_expected_loose), length(l_extracted_loose)) /
                          greatest(length(l_expected_loose), length(l_extracted_loose));
        if l_expected_loose = l_extracted_loose
           or ((instr(l_expected_loose, l_extracted_loose) > 0
                or instr(l_extracted_loose, l_expected_loose) > 0)
               and l_length_ratio >= 0.70) then
          l_status := 'MATCH';
          l_detail := 'Case, spacing, punctuation, and short regulatory prefixes are ignored.';
        else
          l_status := 'MISMATCH';
          l_detail := 'The producer/address text differs materially or is incomplete.';
        end if;
      end if;
    end if;
    add_result(p_verification_id, 50, 'PRODUCER', 'Bottler / producer',
               p_expected_producer, p_extracted_producer,
               l_status, p_confidence, l_detail);

    if p_expected_country is null then
      l_status := 'NOT_APPLICABLE';
      l_detail := 'Country of origin was not supplied; this may be a domestic product.';
    elsif p_extracted_country is null then
      l_status := 'MISSING';
      l_detail := 'No country of origin could be read from the label.';
    elsif normalize_loose(p_expected_country) = normalize_loose(p_extracted_country) then
      l_status := 'MATCH';
      l_detail := 'Case, spacing, and punctuation differences are ignored.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The country of origin differs from the application.';
    end if;
    add_result(p_verification_id, 60, 'COUNTRY', 'Country of origin',
               p_expected_country, p_extracted_country,
               l_status, p_confidence, l_detail);

    if p_extracted_warning is null then
      l_status := 'MISSING';
      l_detail := 'The mandatory government warning was not detected.';
    elsif normalize_whitespace(p_extracted_warning) = normalize_whitespace(c_warning) then
      l_status := 'MATCH';
      l_detail := 'The wording and punctuation match after normalizing line breaks and repeated spaces.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The warning must match the mandatory wording exactly; only whitespace is normalized.';
    end if;
    add_result(p_verification_id, 70, 'WARNING_TEXT', 'Government warning text',
               c_warning, p_extracted_warning,
               l_status, p_confidence, l_detail);

    if p_extracted_warning is null then
      l_status := 'MISSING';
      l_detail := 'The warning heading was not detected.';
    elsif p_warning_heading_all_caps = 'Y'
          and regexp_like(ltrim(p_extracted_warning), '^GOVERNMENT WARNING:') then
      l_status := 'MATCH';
      l_detail := 'The heading is presented in capital letters.';
    elsif p_warning_heading_all_caps is null then
      l_status := 'REVIEW';
      l_detail := 'The extraction service could not determine heading capitalization reliably.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The heading must begin with GOVERNMENT WARNING: in capital letters.';
    end if;
    add_result(p_verification_id, 80, 'WARNING_CAPS', 'Warning heading capitalization',
               'GOVERNMENT WARNING: (all caps)',
               case p_warning_heading_all_caps when 'Y' then 'All caps' when 'N' then 'Not all caps' end,
               l_status, p_confidence, l_detail);

    if p_extracted_warning is null then
      l_status := 'MISSING';
      l_detail := 'The warning heading was not detected.';
    elsif p_warning_heading_bold = 'Y' then
      l_status := 'MATCH';
      l_detail := 'The first two words are visually bold.';
    elsif p_warning_heading_bold is null then
      l_status := 'REVIEW';
      l_detail := 'The extraction service could not determine bold styling reliably.';
    else
      l_status := 'MISMATCH';
      l_detail := 'GOVERNMENT WARNING must be in bold type.';
    end if;
    add_result(p_verification_id, 90, 'WARNING_BOLD', 'Warning heading bold',
               'Bold',
               case p_warning_heading_bold when 'Y' then 'Bold' when 'N' then 'Not bold' end,
               l_status, p_confidence, l_detail);

    if p_confidence is null then
      l_status := 'REVIEW';
      l_detail := 'The extraction provider did not return a confidence score.';
    elsif p_confidence < coalesce(l_min_confidence, 0.75) then
      l_status := 'REVIEW';
      l_detail := 'Low-confidence results require human review even when field values appear to match.';
    else
      l_status := 'MATCH';
      l_detail := 'The extraction confidence meets the configured threshold.';
    end if;
    add_result(p_verification_id, 100, 'CONFIDENCE', 'Extraction confidence',
               '>=' || to_char(coalesce(l_min_confidence, 0.75) * 100, 'FM990D0') || '%',
               case when p_confidence is not null
                    then to_char(p_confidence * 100, 'FM990D0') || '%'
               end,
               l_status, p_confidence, l_detail);

    select sum(case when match_status in ('MISMATCH', 'MISSING') then 1 else 0 end),
           sum(case when match_status = 'REVIEW' then 1 else 0 end)
      into l_fail_count, l_review_count
      from alv_verification_fields
     where verification_id = p_verification_id;

    -- Extraction reliability takes precedence over apparent mismatches. A low-
    -- confidence or missing-confidence extraction must be reviewed by a person;
    -- it must not automatically reject a label based on uncertain evidence.
    if p_confidence is null
       or p_confidence < coalesce(l_min_confidence, 0.75) then
      p_overall_status := 'REVIEW';
    elsif coalesce(l_fail_count, 0) > 0 then
      p_overall_status := 'FAIL';
    elsif coalesce(l_review_count, 0) > 0 then
      p_overall_status := 'REVIEW';
    else
      p_overall_status := 'PASS';
    end if;
  end build_results;

  procedure demo_extract(
    p_profile                    in varchar2,
    p_expected_brand_name        in varchar2,
    p_expected_class_type        in varchar2,
    p_expected_abv               in number,
    p_expected_net_contents      in varchar2,
