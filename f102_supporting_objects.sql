  function strip_code_fence(p_text in varchar2) return varchar2 is
    l_text varchar2(32767) := trim(p_text);
  begin
    if substr(l_text, 1, 3) = '```' then
      l_text := regexp_replace(l_text, '^```[[:alpha:]]*[[:space:]]*', '');
      l_text := regexp_replace(l_text, '[[:space:]]*```$', '');
    end if;
    return trim(l_text);
  end strip_code_fence;

  procedure openai_extract(
    p_mime_type                  in varchar2,
    p_image_blob                 in blob,
    p_brand_name                 out varchar2,
    p_class_type                 out varchar2,
    p_abv                        out number,
    p_net_contents               out varchar2,
    p_producer                   out varchar2,
    p_country                    out varchar2,
    p_warning                    out varchar2,
    p_warning_all_caps           out char,
    p_warning_bold               out char,
    p_raw_text                   out clob,
    p_confidence                 out number,
    p_http_status                out number,
    p_provider_response          out clob
  ) is
    l_endpoint       varchar2(4000) := get_config('OPENAI_ENDPOINT');
    l_credential     varchar2(255)  := get_config('OPENAI_CREDENTIAL_STATIC_ID');
    l_model          varchar2(255)  := get_config('OPENAI_MODEL', 'gpt-5.6');
    l_timeout        number         := safe_number(get_config('API_TIMEOUT_SECONDS', '12'));
    l_prompt         varchar2(32767);
    l_base64         clob;
    l_request        clob;
    l_response       clob;
    l_root           json_object_t;
    l_choices        json_array_t;
    l_choice         json_object_t;
    l_message        json_object_t;
    l_content        varchar2(32767);
    l_result         json_object_t;
    l_bool           boolean;
  begin
    if l_endpoint is null or l_credential is null or l_model is null then
      raise_application_error(-20030, 'Live provider configuration is incomplete.');
    end if;

    l_prompt :=
      'Read this alcohol beverage label. Return ONLY one valid JSON object with exactly these keys: ' ||
      'brand_name, class_type, abv_percent, net_contents, producer_name_address, country_of_origin, ' ||
      'government_warning_text, government_warning_heading_all_caps, government_warning_heading_bold, ' ||
      'raw_text, confidence. Use JSON null for unreadable values. abv_percent must be a number, and ' ||
      'confidence must be from 0 to 1. Preserve the government warning wording, capitalization, and ' ||
      'punctuation exactly as seen; do not correct or normalize it. Inspect the image itself to decide ' ||
      'whether the words GOVERNMENT WARNING are all capitals and visually bold. Do not infer missing text.';

    l_base64 := apex_web_service.blob2clobbase64(
      p_blob     => p_image_blob,
      p_newlines => 'N',
      p_padding  => 'Y'
    );

    dbms_lob.createtemporary(l_request, true, dbms_lob.call);
    append_text(
      l_request,
      '{"model":' || apex_json.stringify(l_model) ||
      ',"messages":[{"role":"user","content":[' ||
      '{"type":"text","text":' || apex_json.stringify(l_prompt) || '},' ||
      '{"type":"image_url","image_url":{"url":"data:' || lower(p_mime_type) || ';base64,'
    );
    dbms_lob.append(l_request, l_base64);
    append_text(
      l_request,
      '"}}]}],"max_completion_tokens":1500,"response_format":{"type":"json_object"}}'
    );

    apex_web_service.g_request_headers.delete;
    apex_web_service.g_request_headers(1).name := 'Content-Type';
    apex_web_service.g_request_headers(1).value := 'application/json';
    apex_web_service.g_request_headers(2).name := 'Accept';
    apex_web_service.g_request_headers(2).value := 'application/json';

    l_response := apex_web_service.make_rest_request(
      p_url                  => l_endpoint,
      p_http_method          => 'POST',
      p_body                 => l_request,
      p_credential_static_id => l_credential,
      p_transfer_timeout     => coalesce(l_timeout, 12)
    );

    p_http_status := apex_web_service.g_status_code;
    p_provider_response := l_response;

    if p_http_status < 200 or p_http_status >= 300 then
      raise_application_error(
        -20031,
        'Vision service returned HTTP ' || p_http_status || ': ' ||
        substr(dbms_lob.substr(l_response, 1000, 1), 1, 1000)
      );
    end if;

    l_root := json_object_t.parse(l_response);
    l_choices := l_root.get_array('choices');
    if l_choices is null or l_choices.get_size = 0 then
      raise_application_error(-20032, 'Vision service response did not contain a choice.');
    end if;

    l_choice := treat(l_choices.get(0) as json_object_t);
    l_message := l_choice.get_object('message');
    l_content := strip_code_fence(l_message.get_string('content'));
    l_result := json_object_t.parse(l_content);

    p_brand_name := l_result.get_string('brand_name');
    p_class_type := l_result.get_string('class_type');
    p_abv := l_result.get_number('abv_percent');
    p_net_contents := l_result.get_string('net_contents');
    p_producer := l_result.get_string('producer_name_address');
    p_country := l_result.get_string('country_of_origin');
    p_warning := l_result.get_string('government_warning_text');

    l_bool := l_result.get_boolean('government_warning_heading_all_caps');
    p_warning_all_caps := bool_to_yn(l_bool);
    l_bool := l_result.get_boolean('government_warning_heading_bold');
    p_warning_bold := bool_to_yn(l_bool);

    p_raw_text := l_result.get_clob('raw_text');
    p_confidence := l_result.get_number('confidence');

    if p_confidence is not null then
      p_confidence := greatest(0, least(1, p_confidence));
    end if;

    if dbms_lob.istemporary(l_base64) = 1 then
      dbms_lob.freetemporary(l_base64);
    end if;
    if dbms_lob.istemporary(l_request) = 1 then
      dbms_lob.freetemporary(l_request);
    end if;
  exception
    when others then
      if l_base64 is not null and dbms_lob.istemporary(l_base64) = 1 then
        dbms_lob.freetemporary(l_base64);
      end if;
      if l_request is not null and dbms_lob.istemporary(l_request) = 1 then
        dbms_lob.freetemporary(l_request);
      end if;
      raise;
  end openai_extract;

  function file_basename(p_path in varchar2) return varchar2 is
    l_path varchar2(4000) := replace(p_path, chr(92), '/');
  begin
    return regexp_substr(l_path, '[^/]+$');
  end file_basename;

  function mime_from_name(p_file_name in varchar2) return varchar2 is
    l_ext varchar2(50) := lower(substr(p_file_name, instr(p_file_name, '.', -1) + 1));
  begin
    return case l_ext
      when 'jpg' then 'image/jpeg'
      when 'jpeg' then 'image/jpeg'
      when 'png' then 'image/png'
      when 'webp' then 'image/webp'
      when 'gif' then 'image/gif'
      else 'application/octet-stream'
    end;
  end mime_from_name;

  function effective_mime(
    p_file_name in varchar2,
    p_mime_type in varchar2
  ) return varchar2 is
    l_mime varchar2(255) := lower(regexp_substr(trim(p_mime_type), '^[^;]+'));
  begin
    if l_mime = 'image/jpg' then
      return 'image/jpeg';
    elsif l_mime in ('image/jpeg', 'image/png', 'image/webp', 'image/gif') then
      return l_mime;
    else
      return mime_from_name(p_file_name);
    end if;
  end effective_mime;

  function normalize_header(p_value in varchar2) return varchar2 is
    l_value varchar2(4000);
  begin
    l_value := lower(trim(replace(p_value, unistr('\FEFF'), '')));
    l_value := regexp_replace(l_value, '[^a-z0-9]+', '_');
    return regexp_replace(l_value, '^_+|_+$', '');
  end normalize_header;

  procedure validate_input(
    p_file_name              in varchar2,
    p_mime_type              in varchar2,
    p_image_blob             in blob,
    p_application_ref        in varchar2,
    p_expected_brand_name    in varchar2,
    p_expected_class_type    in varchar2,
    p_expected_abv           in number,
    p_expected_net_contents  in varchar2,
    p_expected_producer      in varchar2,
    p_is_demo                in boolean
  ) is
    l_max_bytes number := safe_number(get_config('MAX_FILE_BYTES', '10485760'));
    l_mime      varchar2(255) := lower(trim(p_mime_type));
  begin
    if trim(p_application_ref) is null then
      raise_application_error(-20001, 'Application reference is required.');
    elsif trim(p_expected_brand_name) is null or normalize_loose(p_expected_brand_name) is null then
      raise_application_error(-20002, 'Expected brand name is required and must contain letters or numbers.');
    elsif trim(p_expected_class_type) is null or normalize_loose(p_expected_class_type) is null then
      raise_application_error(-20003, 'Expected class/type is required and must contain letters or numbers.');
    elsif p_expected_abv is null or p_expected_abv < 0 or p_expected_abv > 100 then
      raise_application_error(-20004, 'Expected ABV must be between 0 and 100.');
    elsif trim(p_expected_net_contents) is null or net_to_ml(p_expected_net_contents) is null then
      raise_application_error(-20005, 'Expected net contents must include a supported number and unit.');
    elsif trim(p_expected_producer) is null or normalize_loose(p_expected_producer) is null then
      raise_application_error(-20006, 'Expected bottler/producer is required and must contain letters or numbers.');
    end if;

    if p_image_blob is null then
      if not p_is_demo then
        raise_application_error(-20007, 'A label image is required for live verification.');
      end if;
    else
      if trim(p_file_name) is null then
        raise_application_error(-20007, 'The uploaded image file name is missing.');
      elsif dbms_lob.getlength(p_image_blob) > coalesce(l_max_bytes, 10485760) then
        raise_application_error(-20008, 'The image exceeds the configured size limit.');
      elsif l_mime not in ('image/jpeg', 'image/png', 'image/webp', 'image/gif') then
        raise_application_error(-20009, 'Upload a JPEG, PNG, WEBP, or GIF image.');
      end if;
    end if;
  end validate_input;

  procedure verify_label(
    p_file_name              in varchar2,
    p_mime_type              in varchar2,
    p_image_blob             in blob,
    p_application_ref        in varchar2,
    p_expected_brand_name    in varchar2,
    p_expected_class_type    in varchar2,
    p_expected_abv           in number,
    p_expected_net_contents  in varchar2,
    p_expected_producer      in varchar2,
    p_expected_country       in varchar2 default null,
    p_demo_profile           in varchar2 default null,
    p_batch_id               in number default null,
    p_verification_id        out number
  ) is
    l_start                      number := dbms_utility.get_time;
    l_provider                   varchar2(30) := upper(get_config('PROVIDER', 'DEMO'));
    l_profile                    varchar2(30) := upper(trim(p_demo_profile));
    l_is_demo                    boolean;
    l_brand_name                 varchar2(500);
    l_class_type                 varchar2(1000);
    l_abv                        number;
    l_net_contents               varchar2(200);
    l_producer                   varchar2(1000);
    l_country                    varchar2(500);
    l_warning                    varchar2(4000);
    l_warning_all_caps           char(1);
    l_warning_bold               char(1);
    l_raw_text                   clob;
    l_confidence                 number;
    l_http_status                number;
    l_provider_response          clob;
    l_overall_status             varchar2(20);
    l_elapsed_ms                 number;
    l_error_message              varchar2(4000);
    l_app_user                   varchar2(255) := app_user;
    l_effective_mime             varchar2(255) := effective_mime(p_file_name, p_mime_type);
  begin
    if l_profile is not null then
      l_provider := 'DEMO';
    end if;

    -- Never disguise an unconfigured live-provider request as a passing demo.
    -- Demo behavior must always be explicitly selected by the caller.
    if l_provider = 'DEMO' and l_profile is null then
      raise_application_error(
        -20011,
        'Live image analysis is not configured. Select a Demo mode or set ALV_CONFIG.PROVIDER to OPENAI and configure the APEX Web Credential.'
      );
    end if;

    l_is_demo := (l_provider = 'DEMO');

    validate_input(
      p_file_name,
      l_effective_mime,
      p_image_blob,
      p_application_ref,
      p_expected_brand_name,
      p_expected_class_type,
      p_expected_abv,
      p_expected_net_contents,
      p_expected_producer,
      l_is_demo
    );

    insert into alv_verifications (
      public_token,
      batch_id,
      application_ref,
      file_name,
      mime_type,
      image_blob,
      expected_brand_name,
      expected_class_type,
      expected_abv,
      expected_net_contents,
      expected_producer,
      expected_country,
      provider,
      demo_profile,
      overall_status,
      created_by
    ) values (
      lower(rawtohex(sys_guid())),
      p_batch_id,
      trim(p_application_ref),
      p_file_name,
      l_effective_mime,
      p_image_blob,
      trim(p_expected_brand_name),
      trim(p_expected_class_type),
      p_expected_abv,
      trim(p_expected_net_contents),
      trim(p_expected_producer),
      trim(p_expected_country),
      l_provider,
      l_profile,
      'PROCESSING',
      l_app_user
    ) returning id into p_verification_id;

    begin
      if l_provider = 'DEMO' then
        demo_extract(
          l_profile,
          p_expected_brand_name,
          p_expected_class_type,
          p_expected_abv,
          p_expected_net_contents,
          p_expected_producer,
          p_expected_country,
          l_brand_name,
          l_class_type,
          l_abv,
          l_net_contents,
          l_producer,
          l_country,
          l_warning,
          l_warning_all_caps,
          l_warning_bold,
          l_raw_text,
          l_confidence
        );
      elsif l_provider = 'OPENAI' then
        openai_extract(
          l_effective_mime,
          p_image_blob,
          l_brand_name,
          l_class_type,
          l_abv,
          l_net_contents,
          l_producer,
          l_country,
          l_warning,
          l_warning_all_caps,
          l_warning_bold,
          l_raw_text,
          l_confidence,
          l_http_status,
          l_provider_response
        );
      else
        raise_application_error(-20010, 'Unsupported provider: ' || l_provider);
      end if;

      build_results(
        p_verification_id,
        p_expected_brand_name,
        p_expected_class_type,
        p_expected_abv,
        p_expected_net_contents,
        p_expected_producer,
        p_expected_country,
        l_brand_name,
        l_class_type,
        l_abv,
        l_net_contents,
        l_producer,
        l_country,
        l_warning,
        l_warning_all_caps,
        l_warning_bold,
        l_confidence,
        l_overall_status
      );

      l_elapsed_ms := round((dbms_utility.get_time - l_start) * 10);

      update alv_verifications
         set extracted_brand_name = l_brand_name,
             extracted_class_type = l_class_type,
             extracted_abv = l_abv,
             extracted_net_contents = l_net_contents,
             extracted_producer = l_producer,
             extracted_country = l_country,
             extracted_warning = l_warning,
             warning_heading_all_caps = l_warning_all_caps,
             warning_heading_bold = l_warning_bold,
             extracted_text = l_raw_text,
             provider_response = l_provider_response,
             overall_status = l_overall_status,
             confidence = l_confidence,
             processing_ms = l_elapsed_ms,
             http_status = l_http_status,
             error_message = null
       where id = p_verification_id;
    exception
      when others then
        l_error_message := substr(sqlerrm, 1, 4000);
        l_elapsed_ms := round((dbms_utility.get_time - l_start) * 10);

        delete from alv_verification_fields
         where verification_id = p_verification_id;

        add_result(
          p_verification_id,
          10,
          'PROVIDER_ERROR',
          'Extraction service',
          'Successful extraction',
          'Error',
          'REVIEW',
          null,
          l_error_message
        );

        update alv_verifications
           set provider_response = l_provider_response,
               overall_status = 'REVIEW',
               processing_ms = l_elapsed_ms,
               http_status = l_http_status,
               error_message = l_error_message
         where id = p_verification_id;
    end;
  end verify_label;

