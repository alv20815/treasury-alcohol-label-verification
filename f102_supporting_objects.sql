Use null for unreadable fields or styling. When l=false, set bt=OTHER and b,t,a,n,p,o,w,wp,u,v,z to null except wp may be false. From "45% Alc./Vol. (90 Proof)", return a=45, never 90. Do not use expected application values to fill missing text.~';

