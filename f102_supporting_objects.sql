declare
  l_error_count number;
  l_first_error varchar2(4000);
begin
  select count(*)
    into l_error_count
    from user_errors
   where name = 'ALV_VERIFICATION_PKG'
     and type in ('PACKAGE', 'PACKAGE BODY');

  if l_error_count > 0 then
    select object_type || ' line ' || line || ', position ' || position || ': ' || text
      into l_first_error
      from (
        select type as object_type, line, position, text
          from user_errors
         where name = 'ALV_VERIFICATION_PKG'
           and type in ('PACKAGE', 'PACKAGE BODY')
         order by sequence
      )
     where rownum = 1;

    raise_application_error(
      -20099,
      'ALV_VERIFICATION_PKG has ' || l_error_count ||
      ' compilation error(s). First error: ' || substr(l_first_error, 1, 3500)
    );
  end if;
end;
