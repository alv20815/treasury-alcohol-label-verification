      raise_application_error(-20031, 'Vision service returned HTTP ' || p_http_status || ': ' || substr(dbms_lob.substr(l_response, 1000, 1), 1, 1000));
    end if;

    l_root := json_object_t.parse(l_response);
    l_choices := l_root.get_array('choices');
    if l_choices is null or l_choices.get_size = 0 then raise_application_error(-20032, 'Vision service response did not contain a choice.'); end if;
    l_choice := treat(l_choices.get(0) as json_object_t);
    l_message := l_choice.get_object('message');
    if l_message is null then raise_application_error(-20033, 'Vision service response did not contain a message.'); end if;
    l_refusal := json_string_or_null(l_message, 'refusal');
    if l_refusal is not null then raise_application_error(-20034, 'Vision service refused the image: ' || substr(l_refusal, 1, 1000)); end if;
    l_content := strip_code_fence(json_string_or_null(l_message, 'content'));
    if l_content is null then raise_application_error(-20035, 'Vision service returned no structured extraction content.'); end if;
