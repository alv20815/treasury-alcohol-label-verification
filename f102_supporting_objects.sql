  procedure build_results(
    p_verification_id              in number,
    p_document_type                in varchar2,
    p_is_alcohol_label             in char,
    p_classification_reason        in varchar2,
    p_classification_confidence    in number,
    p_expected_beverage_type       in varchar2,
    p_abv_required                 in char,
    p_extracted_beverage_type      in varchar2,
    p_expected_brand_name          in varchar2,
    p_expected_class_type          in varchar2,
    p_expected_abv                 in number,
    p_expected_net_contents        in varchar2,
    p_expected_producer            in varchar2,
    p_expected_country             in varchar2,
    p_extracted_brand_name         in varchar2,
    p_extracted_class_type         in varchar2,
    p_extracted_abv                in number,
    p_extracted_net_contents       in varchar2,
    p_extracted_producer           in varchar2,
    p_extracted_country            in varchar2,
    p_extracted_warning            in varchar2,
    p_warning_present              in char,
    p_warning_heading_all_caps     in char,
    p_warning_heading_bold         in char,
    p_warning_legible              in char,
    p_confidence                   in number,
    p_overall_status               out varchar2
  ) is
    l_status               varchar2(30);
    l_detail               varchar2(4000);
    l_expected_ml          number;
    l_extracted_ml         number;
    l_min_confidence       number := safe_number(get_config('MIN_CONFIDENCE', '0.75'));
    l_min_class_confidence number := safe_number(get_config('MIN_CLASSIFICATION_CONFIDENCE', '0.80'));
    l_abv_tolerance        number := safe_number(get_config('ABV_TOLERANCE', '0.05'));
    l_net_tolerance        number := safe_number(get_config('NET_TOLERANCE_ML', '2'));
    l_fail_count           number;
    l_review_count         number;
    l_classification_text  varchar2(4000);
    l_expected_beverage    varchar2(30) := normalize_beverage_type(p_expected_beverage_type);
    l_extracted_beverage   varchar2(30) := normalize_beverage_type(p_extracted_beverage_type);
    l_abv_is_required      char(1) := normalize_yes_no(p_abv_required, 'Y');
    l_warning_is_present   char(1) := p_warning_present;
  begin
    delete from alv_verification_fields
     where verification_id = p_verification_id;

    l_classification_text := coalesce(
      trim(p_document_type),
      case upper(trim(p_is_alcohol_label))
        when 'Y' then 'Alcohol beverage label'
        when 'N' then 'Not an alcohol beverage label'
        else 'Unknown'
      end
    );

    if p_is_alcohol_label is null or p_classification_confidence is null then
      l_status := 'REVIEW';
      l_detail := 'The provider did not return a reliable document classification.';
      if p_classification_reason is not null then l_detail := l_detail || ' ' || p_classification_reason; end if;
      add_result(p_verification_id, 5, 'DOCUMENT_CLASSIFICATION', 'Document classification',
                 'Alcohol beverage label', l_classification_text, l_status,
                 p_classification_confidence, l_detail);
      p_overall_status := 'REVIEW';
      return;
    elsif p_classification_confidence < coalesce(l_min_class_confidence, 0.80) then
      l_status := 'REVIEW';
      l_detail := 'Document classification confidence is below the configured threshold.';
      if p_classification_reason is not null then l_detail := l_detail || ' ' || p_classification_reason; end if;
      add_result(p_verification_id, 5, 'DOCUMENT_CLASSIFICATION', 'Document classification',
                 'Alcohol beverage label', l_classification_text, l_status,
                 p_classification_confidence, l_detail);
      p_overall_status := 'REVIEW';
      return;
    elsif upper(trim(p_is_alcohol_label)) = 'N' then
      l_status := 'MISMATCH';
      l_detail := 'The uploaded pixels were confidently classified as something other than an alcohol beverage label.';
      if p_classification_reason is not null then l_detail := l_detail || ' ' || p_classification_reason; end if;
      add_result(p_verification_id, 5, 'DOCUMENT_CLASSIFICATION', 'Document classification',
                 'Alcohol beverage label', l_classification_text, l_status,
                 p_classification_confidence, l_detail);
      p_overall_status := 'FAIL';
      return;
    else
      l_detail := 'The uploaded pixels were classified as an alcohol beverage label.';
      if p_classification_reason is not null then l_detail := l_detail || ' ' || p_classification_reason; end if;
      add_result(p_verification_id, 5, 'DOCUMENT_CLASSIFICATION', 'Document classification',
                 'Alcohol beverage label', l_classification_text, 'MATCH',
                 p_classification_confidence, l_detail);
    end if;

    if l_extracted_beverage is null or l_extracted_beverage = 'OTHER' then
      l_status := 'REVIEW';
      l_detail := 'The label is alcoholic, but its beverage category could not be determined reliably.';
    elsif l_expected_beverage = l_extracted_beverage then
      l_status := 'MATCH';
      l_detail := 'The detected beverage category matches the application category.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The detected beverage category differs from the application category.';
    end if;
    add_result(p_verification_id, 8, 'BEVERAGE_TYPE', 'Beverage category',
               beverage_label(l_expected_beverage), beverage_label(l_extracted_beverage),
               l_status, p_classification_confidence, l_detail);

    if p_extracted_brand_name is null then
      l_status := 'MISSING';
      l_detail := 'No brand name could be read from the label.';
    elsif normalize_loose(p_expected_brand_name) = normalize_loose(p_extracted_brand_name) then
      l_status := 'MATCH';
      l_detail := 'Case, spacing, and punctuation differences are intentionally ignored.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The normalized brand names differ.';
    end if;
    add_result(p_verification_id, 10, 'BRAND_NAME', 'Brand name',
               p_expected_brand_name, p_extracted_brand_name,
               l_status, p_confidence, l_detail);

    if p_extracted_class_type is null then
      l_status := 'MISSING';
      l_detail := 'No class/type designation could be read from the label.';
    elsif normalize_loose(p_expected_class_type) = normalize_loose(p_extracted_class_type) then
      l_status := 'MATCH';
      l_detail := 'Case, spacing, and punctuation differences are ignored.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The normalized class/type designations differ.';
    end if;
    add_result(p_verification_id, 20, 'CLASS_TYPE', 'Class / type',
               p_expected_class_type, p_extracted_class_type,
               l_status, p_confidence, l_detail);

    if l_abv_is_required = 'N' then
      l_status := 'NOT_APPLICABLE';
      l_detail := 'The application marks alcohol-content comparison as not applicable for this beer or wine record. The prototype does not infer legal exceptions.';
    elsif p_extracted_abv is null then
      l_status := 'MISSING';
      l_detail := 'No ABV percentage could be read from the label.';
    elsif abs(p_expected_abv - p_extracted_abv) <= coalesce(l_abv_tolerance, 0.05) then
      l_status := 'MATCH';
      l_detail := 'Compared numerically using the configured ABV tolerance. Proof is not treated as ABV.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The extracted ABV differs from the application value.';
    end if;
    add_result(p_verification_id, 30, 'ABV', 'Alcohol by volume',
               case when l_abv_is_required = 'N' then 'Not applicable for this application' else to_char(p_expected_abv, 'FM990D999') || '%' end,
               case when p_extracted_abv is not null then to_char(p_extracted_abv, 'FM990D999') || '%' end,
               l_status, p_confidence, l_detail);

    l_expected_ml := net_to_ml(p_expected_net_contents);
    l_extracted_ml := net_to_ml(p_extracted_net_contents);
    if p_extracted_net_contents is null then
      l_status := 'MISSING';
      l_detail := 'No net-contents declaration could be read.';
    elsif l_expected_ml is null or l_extracted_ml is null then
      l_status := 'REVIEW';
      l_detail := 'A net-contents value could not be converted to a supported unit.';
    elsif abs(l_expected_ml - l_extracted_ml) <= coalesce(l_net_tolerance, 2) then
      l_status := 'MATCH';
      l_detail := 'Values were converted to milliliters before comparison.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The unit-normalized net contents differ.';
    end if;
    add_result(p_verification_id, 40, 'NET_CONTENTS', 'Net contents',
               p_expected_net_contents, p_extracted_net_contents,
               l_status, p_confidence, l_detail);

    if p_extracted_producer is null then
      l_status := 'MISSING';
      l_detail := 'No bottler/producer name and address could be read.';
    elsif normalize_producer(p_expected_producer) is null or normalize_producer(p_extracted_producer) is null then
      l_status := 'REVIEW';
      l_detail := 'The producer/address text could not be normalized safely.';
    elsif normalize_producer(p_expected_producer) = normalize_producer(p_extracted_producer) then
      l_status := 'MATCH';
      l_detail := 'Only an approved leading regulatory phrase and case/punctuation differences are ignored.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The producer/address differs materially or is incomplete.';
    end if;
    add_result(p_verification_id, 50, 'PRODUCER', 'Bottler / producer',
               p_expected_producer, p_extracted_producer,
               l_status, p_confidence, l_detail);

    if trim(p_expected_country) is null then
      l_status := 'NOT_APPLICABLE';
      l_detail := 'Country of origin is not required for this domestic application example.';
    elsif p_extracted_country is null then
      l_status := 'MISSING';
      l_detail := 'The application expects an import country, but none could be read.';
    elsif normalize_loose(p_expected_country) = normalize_loose(p_extracted_country) then
      l_status := 'MATCH';
      l_detail := 'Country names match after case, spacing, and punctuation normalization.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The extracted country of origin differs from the application value.';
    end if;
    add_result(p_verification_id, 60, 'COUNTRY_OF_ORIGIN', 'Country of origin',
               p_expected_country, p_extracted_country,
               l_status, p_confidence, l_detail);

    if l_warning_is_present is null then
      l_warning_is_present := case when p_extracted_warning is null then 'N' else 'Y' end;
    end if;

    if l_warning_is_present = 'N' or p_extracted_warning is null then
      l_status := 'MISSING';
      l_detail := 'The mandatory government warning was not detected.';
    elsif l_warning_is_present = 'Y' then
      l_status := 'MATCH';
      l_detail := 'A government warning statement is present.';
    else
      l_status := 'REVIEW';
      l_detail := 'Warning presence could not be determined reliably.';
    end if;
    add_result(p_verification_id, 65, 'WARNING_PRESENCE', 'Government warning present',
               'Present', case when l_warning_is_present = 'Y' then 'Present' when l_warning_is_present = 'N' then 'Missing' else 'Uncertain' end,
               l_status, p_confidence, l_detail);

    if l_warning_is_present = 'N' or p_extracted_warning is null then
      l_status := 'MISSING';
      l_detail := 'Exact wording cannot match because the warning is absent.';
    elsif normalize_whitespace(p_extracted_warning) = normalize_whitespace(c_warning) then
      l_status := 'MATCH';
      l_detail := 'The wording and punctuation match after normalizing line breaks and repeated spaces only.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The warning is present but does not match the required wording exactly.';
    end if;
    add_result(p_verification_id, 70, 'WARNING_TEXT', 'Government warning text',
               c_warning, p_extracted_warning,
               l_status, p_confidence, l_detail);

    if l_warning_is_present = 'N' then
      l_status := 'MISSING';
      l_detail := 'The warning heading is absent.';
    elsif p_warning_heading_all_caps is null then
      l_status := 'REVIEW';
      l_detail := 'The heading capitalization could not be determined reliably.';
    elsif p_warning_heading_all_caps = 'Y' then
      l_status := 'MATCH';
      l_detail := 'The warning heading is presented in all capital letters.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The warning heading is not in all capital letters.';
    end if;
    add_result(p_verification_id, 80, 'WARNING_CAPS', 'Warning heading capitalization',
               'GOVERNMENT WARNING: (all caps)',
               case p_warning_heading_all_caps when 'Y' then 'All caps' when 'N' then 'Not all caps' else null end,
               l_status, p_confidence, l_detail);

    if l_warning_is_present = 'N' then
      l_status := 'MISSING';
      l_detail := 'The warning heading is absent.';
    elsif p_warning_heading_bold is null then
      l_status := 'REVIEW';
      l_detail := 'Bold presentation could not be determined reliably.';
    elsif p_warning_heading_bold = 'Y' then
      l_status := 'MATCH';
      l_detail := 'The warning heading is visibly bold.';
    else
      l_status := 'MISMATCH';
      l_detail := 'The warning heading is not visibly bold.';
    end if;
    add_result(p_verification_id, 90, 'WARNING_BOLD', 'Warning heading bold',
               'Bold', case p_warning_heading_bold when 'Y' then 'Bold' when 'N' then 'Not bold' else null end,
               l_status, p_confidence, l_detail);

    if l_warning_is_present = 'N' then
      l_status := 'MISSING';
      l_detail := 'Legibility cannot be evaluated because the warning is absent.';
    elsif p_warning_legible = 'Y' then
      l_status := 'MATCH';
      l_detail := 'The warning is readable and visually distinguishable in the supplied artwork.';
    else
      l_status := 'REVIEW';
      l_detail := 'The prototype cannot confirm warning legibility or conspicuousness. Human review is required; no legal font-size threshold is inferred.';
    end if;
    add_result(p_verification_id, 95, 'WARNING_LEGIBILITY', 'Warning legibility / conspicuousness',
               'Readable and conspicuous', case p_warning_legible when 'Y' then 'Readable' when 'N' then 'Not reliably readable' else 'Uncertain' end,
               l_status, p_confidence, l_detail);

    if p_confidence is null or p_confidence < coalesce(l_min_confidence, 0.75) then
      l_status := 'REVIEW';
      l_detail := 'Extraction confidence is below the configured threshold.';
    else
      l_status := 'MATCH';
      l_detail := 'Extraction confidence meets the configured threshold.';
    end if;
    add_result(p_verification_id, 100, 'EXTRACTION_CONFIDENCE', 'Extraction confidence',
               '>= ' || to_char(coalesce(l_min_confidence, 0.75) * 100, 'FM990D0') || '%',
               case when p_confidence is not null then to_char(p_confidence * 100, 'FM990D0') || '%' end,
               l_status, p_confidence, l_detail);

    select sum(case when match_status in ('MISMATCH', 'MISSING') then 1 else 0 end),
           sum(case when match_status = 'REVIEW' then 1 else 0 end)
      into l_fail_count, l_review_count
      from alv_verification_fields
     where verification_id = p_verification_id;

    if coalesce(l_fail_count, 0) > 0 then
      p_overall_status := 'FAIL';
    elsif coalesce(l_review_count, 0) > 0 then
      p_overall_status := 'REVIEW';
    else
      p_overall_status := 'PASS';
    end if;
  end build_results;

