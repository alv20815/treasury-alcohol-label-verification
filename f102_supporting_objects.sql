      'Built-in rollback-safe-style acceptance workload: 60 PASS, 180 FAIL, and 60 REVIEW expected.'
    ) returning id into p_batch_id;

    for i in 1 .. 300 loop
      l_profile := case mod(i - 1, 20)
        when 0 then 'PASS_SPIRITS'
        when 1 then 'PASS_WINE'
        when 2 then 'PASS_BEER'
        when 3 then 'IMPORT_COUNTRY_MATCH'
        when 4 then 'BRAND_MISMATCH'
        when 5 then 'CLASS_TYPE_MISMATCH'
        when 6 then 'BEVERAGE_TYPE_MISMATCH'
        when 7 then 'ABV_MISMATCH'
        when 8 then 'MISSING_ABV'
        when 9 then 'NET_CONTENTS_MISMATCH'
        when 10 then 'PRODUCER_MISMATCH'
        when 11 then 'IMPORT_COUNTRY_MISMATCH'
        when 12 then 'WARNING_ERROR'
        when 13 then 'MISSING_WARNING'
        when 14 then 'CAPS_ONLY_ERROR'
        when 15 then 'BOLD_ONLY_ERROR'
        when 16 then 'LOW_CONFIDENCE'
        when 17 then 'WARNING_LEGIBILITY_REVIEW'
        when 18 then 'UNREADABLE_IMAGE'
        else 'TYPOGRAPHY_UNCERTAIN'
      end;

      select image_file_name, beverage_type, abv_required,
             expected_brand_name, expected_class_type, expected_abv,
             expected_net_contents, expected_producer, expected_country
        into l_file_name, l_beverage, l_abv_required,
             l_brand, l_class_type, l_abv,
             l_net, l_producer, l_country
        from alv_demo_scenarios
       where profile_code = l_profile
         and active_yn = 'Y';

      verify_label(
        p_file_name => l_file_name,
        p_mime_type => 'image/png',
        p_image_blob => null,
        p_application_ref => 'BATCH300-' || to_char(i, 'FM000'),
        p_beverage_type => l_beverage,
        p_abv_required => l_abv_required,
        p_expected_brand_name => l_brand,
        p_expected_class_type => l_class_type,
        p_expected_abv => l_abv,
        p_expected_net_contents => l_net,
        p_expected_producer => l_producer,
        p_expected_country => l_country,
        p_demo_profile => l_profile,
        p_batch_id => p_batch_id,
        p_verification_id => l_verification_id
      );
    end loop;

    select count(*),
           sum(case when overall_status = 'PASS' then 1 else 0 end),
           sum(case when overall_status = 'FAIL' then 1 else 0 end),
           sum(case when overall_status = 'REVIEW' then 1 else 0 end)
      into l_processed, l_pass, l_fail, l_review
      from alv_verifications
     where batch_id = p_batch_id;

    l_elapsed_ms := round((dbms_utility.get_time - l_start) * 10);

    update alv_batches
       set status = 'COMPLETED',
           processed_count = l_processed,
           pass_count = l_pass,
           fail_count = l_fail,
           review_count = l_review,
           processing_ms = l_elapsed_ms,
           completed_at = systimestamp,
           notes = 'Built-in deterministic 300-row acceptance test. Expected and actual counts: 60 PASS, 180 FAIL, 60 REVIEW.'
     where id = p_batch_id;

    if l_processed != 300 or l_pass != 60 or l_fail != 180 or l_review != 60 then
      raise_application_error(
        -20061,
        'Built-in 300-row test produced unexpected counts: processed=' || l_processed ||
        ', pass=' || l_pass || ', fail=' || l_fail || ', review=' || l_review || '.'
      );
    end if;
  exception
    when others then
      l_error_message := substr(sqlerrm, 1, 4000);
      if p_batch_id is not null then
        update alv_batches
           set status = 'FAILED',
               completed_at = systimestamp,
               processing_ms = round((dbms_utility.get_time - l_start) * 10),
               notes = l_error_message
         where id = p_batch_id;
      end if;
      raise;
  end create_demo_batch_300;

  procedure insert_batch_error(
    p_batch_id           in number,
    p_application_ref    in varchar2,
    p_file_name          in varchar2,
    p_beverage_type      in varchar2,
    p_abv_required       in char,
    p_brand_name         in varchar2,
    p_class_type         in varchar2,
    p_abv                in number,
    p_net_contents       in varchar2,
    p_producer           in varchar2,
    p_country            in varchar2,
    p_message            in varchar2
  ) is
    l_id                  number;
    l_app_user            varchar2(255) := app_user;
    l_beverage_type_norm  varchar2(30);
    l_abv_required_norm   char(1);
  begin
    l_beverage_type_norm := coalesce(
      normalize_beverage_type(p_beverage_type),
      'DISTILLED_SPIRITS'
    );
    l_abv_required_norm := normalize_yes_no(p_abv_required, 'Y');

    insert into alv_verifications (
      public_token, batch_id, application_ref, file_name, beverage_type, abv_required,
      expected_brand_name, expected_class_type, expected_abv, expected_net_contents,
      expected_producer, expected_country, provider, overall_status, error_message, created_by
    ) values (
      lower(rawtohex(sys_guid())), p_batch_id,
      coalesce(trim(p_application_ref), 'UNIDENTIFIED'), p_file_name,
      l_beverage_type_norm,
      l_abv_required_norm,
      p_brand_name, p_class_type, p_abv, p_net_contents, p_producer, p_country,
      'BATCH', 'REVIEW', substr(p_message, 1, 4000), l_app_user
    ) returning id into l_id;
    add_result(l_id, 10, 'BATCH_INPUT', 'Batch input',
               'Valid manifest row and matching image', 'Input error',
               'REVIEW', null, p_message);
  end insert_batch_error;

  procedure process_batch(
    p_manifest_file_name  in varchar2,
    p_manifest_blob       in blob,
    p_zip_file_name       in varchar2,
    p_zip_blob            in blob,
    p_processing_mode     in varchar2,
    p_batch_id            out number
  ) is
    l_start             number := dbms_utility.get_time;
    l_mode              varchar2(30) := upper(coalesce(trim(p_processing_mode), 'CONFIGURED'));
    l_provider          varchar2(30) := upper(get_config('PROVIDER', 'DEMO'));
    l_max_items         number := safe_number(get_config('MAX_BATCH_ITEMS', '300'));
    l_live_limit        number := safe_number(get_config('MAX_SYNC_LIVE_BATCH_ITEMS', '25'));
    l_max_manifest      number := safe_number(get_config('MAX_MANIFEST_BYTES', '2097152'));
    l_max_zip           number := safe_number(get_config('MAX_BATCH_ZIP_BYTES', '104857600'));
    l_max_uncompressed  number := safe_number(get_config('MAX_BATCH_UNCOMPRESSED_BYTES', '314572800'));
    l_max_file          number := safe_number(get_config('MAX_FILE_BYTES', '10485760'));
    l_manifest_count    number;
    l_zip_entries       apex_zip.t_dir_entries;
    l_zip_key           varchar2(32767);
    l_zip_entry         varchar2(32767);
    l_image_blob        blob;
    l_mime_type         varchar2(255);
    l_demo_profile      varchar2(30);
    l_verification_id   number;
    l_row_number        number := 0;
    l_abv               number;
    l_beverage_type     varchar2(30);
    l_abv_required      char(1);
    l_processed         number;
    l_pass              number;
    l_fail              number;
    l_review            number;
    l_elapsed_ms        number;
    l_uncompressed_total number := 0;
    l_match_count       number;
    l_lookup_error      varchar2(4000);
    l_h1                varchar2(100);
    l_h2                varchar2(100);
    l_h3                varchar2(100);
    l_h4                varchar2(100);
    l_h5                varchar2(100);
    l_h6                varchar2(100);
    l_h7                varchar2(100);
    l_h8                varchar2(100);
    l_h9                varchar2(100);
    l_h10               varchar2(100);
    l_h11               varchar2(100);
    l_error_message      varchar2(4000);
    l_app_user           varchar2(255) := app_user;
  begin
    if p_manifest_blob is null then
      raise_application_error(-20040, 'A CSV manifest is required.');
    elsif p_zip_blob is null then
      raise_application_error(-20041, 'A ZIP archive containing label images is required.');
    elsif trim(p_manifest_file_name) is null or lower(p_manifest_file_name) not like '%.csv' then
      raise_application_error(-20047, 'The manifest must be a CSV file.');
    elsif trim(p_zip_file_name) is null or lower(p_zip_file_name) not like '%.zip' then
      raise_application_error(-20048, 'The image archive must be a ZIP file.');
    elsif dbms_lob.getlength(p_manifest_blob) > coalesce(l_max_manifest, 2097152) then
      raise_application_error(-20049, 'The CSV manifest exceeds the configured size limit.');
    elsif dbms_lob.getlength(p_zip_blob) > coalesce(l_max_zip, 104857600) then
      raise_application_error(-20051, 'The ZIP archive exceeds the configured compressed size limit.');
    elsif l_mode not in ('CONFIGURED', 'DEMO_MANIFEST', 'DEMO_MIXED', 'PASS', 'PASS_SPIRITS', 'PASS_WINE', 'PASS_BEER', 'ABV_NOT_APPLICABLE_WINE', 'ABV_NOT_APPLICABLE_BEER', 'IMPORT_COUNTRY_MATCH', 'BRAND_MISMATCH', 'CLASS_TYPE_MISMATCH', 'BEVERAGE_TYPE_MISMATCH', 'ABV_MISMATCH', 'MISSING_ABV', 'NET_CONTENTS_MISMATCH', 'PRODUCER_MISMATCH', 'IMPORT_COUNTRY_MISMATCH', 'WARNING_ERROR', 'MISSING_WARNING', 'CAPS_ONLY_ERROR', 'BOLD_ONLY_ERROR', 'LOW_CONFIDENCE', 'WARNING_LEGIBILITY_REVIEW', 'UNREADABLE_IMAGE', 'TYPOGRAPHY_UNCERTAIN', 'NON_ALCOHOL') then
      raise_application_error(-20042, 'Unsupported batch processing mode: ' || l_mode);
    elsif l_mode = 'CONFIGURED' and l_provider = 'DEMO' then
      raise_application_error(
        -20058,
        'Live batch analysis is not configured. Select a Demo mode or set ALV_CONFIG.PROVIDER to OPENAI and configure the APEX Web Credential.'
      );
    end if;

    insert into alv_batches (
      public_token,
      manifest_file_name,
      zip_file_name,
      processing_mode,
      status,
      started_at,
      created_by
    ) values (
      lower(rawtohex(sys_guid())),
      p_manifest_file_name,
      p_zip_file_name,
      l_mode,
      'PROCESSING',
      systimestamp,
      l_app_user
    ) returning id into p_batch_id;

    begin
      begin
        select col001, col002, col003, col004, col005, col006, col007, col008, col009, col010, col011
          into l_h1, l_h2, l_h3, l_h4, l_h5, l_h6, l_h7, l_h8, l_h9, l_h10, l_h11
          from table(
            apex_data_parser.parse(
              p_content                => p_manifest_blob,
              p_file_name              => p_manifest_file_name,
              p_detect_data_types      => 'N',
              p_force_trim_whitespace  => 'Y',
              p_max_rows               => 1
            )
          )
         where line_number = 1;
      exception
        when no_data_found then
          raise_application_error(-20052, 'The manifest is empty or cannot be parsed.');
      end;

      l_h1 := normalize_header(l_h1);
      l_h2 := normalize_header(l_h2);
      l_h3 := normalize_header(l_h3);
      l_h4 := normalize_header(l_h4);
      l_h5 := normalize_header(l_h5);
      l_h6 := normalize_header(l_h6);
      l_h7 := normalize_header(l_h7);
      l_h8 := normalize_header(l_h8);
      l_h9 := normalize_header(l_h9);
      l_h10 := normalize_header(l_h10);
      l_h11 := normalize_header(l_h11);

      if coalesce(l_h1, '~') != 'file_name'
         or coalesce(l_h2, '~') != 'application_ref'
         or coalesce(l_h3, '~') not in ('beverage_type', 'beverage_category')
         or coalesce(l_h4, '~') not in ('abv_required', 'alcohol_content_required')
         or coalesce(l_h5, '~') != 'brand_name'
         or coalesce(l_h6, '~') not in ('class_type', 'class_or_type')
         or coalesce(l_h7, '~') not in ('abv', 'abv_percent')
         or coalesce(l_h8, '~') != 'net_contents'
         or coalesce(l_h9, '~') not in ('producer', 'producer_name_address', 'bottler_producer')
         or coalesce(l_h10, '~') not in ('country', 'country_of_origin')
         or coalesce(l_h11, '~') != 'demo_profile' then
        raise_application_error(
          -20053,
          'Unexpected manifest headers. Use: file_name, application_ref, beverage_type, abv_required, brand_name, class_type, abv, net_contents, producer, country, demo_profile.'
        );
      end if;

      select count(*)
        into l_manifest_count
        from table(
          apex_data_parser.parse(
            p_content                => p_manifest_blob,
            p_file_name              => p_manifest_file_name,
            p_detect_data_types      => 'N',
            p_force_trim_whitespace  => 'Y',
            -- Count the complete size-limited manifest. Omitting p_max_rows
            -- avoids header/skip off-by-one behavior and lets 301+ rows be rejected.
            p_skip_rows              => 1
          )
        )
       where col001 is not null
          or col002 is not null
          or col003 is not null
          or col004 is not null
          or col005 is not null
          or col006 is not null
          or col007 is not null
          or col008 is not null
          or col009 is not null
          or col010 is not null
          or col011 is not null;

      update alv_batches
         set total_count = l_manifest_count
       where id = p_batch_id;

      if l_manifest_count = 0 then
        raise_application_error(-20043, 'The manifest contains no data rows.');
      elsif l_manifest_count > coalesce(l_max_items, 300) then
        raise_application_error(-20044, 'The manifest exceeds the configured maximum of ' || coalesce(l_max_items, 300) || ' rows.');
      elsif l_mode = 'CONFIGURED'
            and l_provider = 'OPENAI'
            and l_manifest_count > coalesce(l_live_limit, 25) then
        raise_application_error(
          -20045,
          'Live synchronous batches are capped at ' || coalesce(l_live_limit, 25) ||
          ' items in this prototype. Use a demo mode or implement queued workers for production.'
        );
      end if;

      l_zip_entries := apex_zip.get_dir_entries(p_zipped_blob => p_zip_blob);
      if l_zip_entries.count = 0 then
        raise_application_error(-20054, 'The ZIP archive contains no files.');
      end if;

      l_zip_key := l_zip_entries.first;
      while l_zip_key is not null loop
        l_uncompressed_total := l_uncompressed_total + coalesce(l_zip_entries(l_zip_key).uncompressed_length, 0);
        if l_uncompressed_total > coalesce(l_max_uncompressed, 314572800) then
          raise_application_error(-20055, 'The ZIP archive exceeds the configured uncompressed size limit.');
        elsif mime_from_name(l_zip_entries(l_zip_key).file_name) != 'application/octet-stream'
              and l_zip_entries(l_zip_key).uncompressed_length > coalesce(l_max_file, 10485760) then
          raise_application_error(-20056, 'A label image in the ZIP exceeds the configured per-file size limit.');
        end if;
        l_zip_key := l_zip_entries.next(l_zip_key);
      end loop;

      for r in (
        select col001 as file_name,
               col002 as application_ref,
               col003 as beverage_type,
               col004 as abv_required,
               col005 as brand_name,
               col006 as class_type,
               col007 as abv,
               col008 as net_contents,
               col009 as producer,
               col010 as country,
               col011 as demo_profile
          from table(
            apex_data_parser.parse(
              p_content                => p_manifest_blob,
              p_file_name              => p_manifest_file_name,
              p_detect_data_types      => 'N',
              p_force_trim_whitespace  => 'Y',
              -- The validated manifest is processed without a second row cap,
              -- so all rows (including row 300) are emitted exactly once.
              p_skip_rows              => 1
            )
          )
         where col001 is not null
            or col002 is not null
            or col003 is not null
            or col004 is not null
            or col005 is not null
            or col006 is not null
            or col007 is not null
            or col008 is not null
            or col009 is not null
            or col010 is not null
            or col011 is not null
         order by line_number
      ) loop
        l_row_number := l_row_number + 1;
        l_zip_entry := null;
        l_image_blob := null;
        l_lookup_error := null;
        l_match_count := 0;
        l_abv := safe_number(r.abv);
        l_beverage_type := normalize_beverage_type(r.beverage_type);
        l_abv_required := normalize_yes_no(r.abv_required, 'Y');

        -- Prefer an exact archive path. If the manifest uses only a base name,
        -- accept it only when that base name is unique within the archive.
        l_zip_key := l_zip_entries.first;
        while l_zip_key is not null loop
          if lower(replace(l_zip_entries(l_zip_key).file_name, chr(92), '/')) =
             lower(replace(trim(r.file_name), chr(92), '/')) then
            l_zip_entry := l_zip_key;
            exit;
          end if;
          l_zip_key := l_zip_entries.next(l_zip_key);
        end loop;

        if l_zip_entry is null then
          l_zip_key := l_zip_entries.first;
          while l_zip_key is not null loop
            if lower(file_basename(l_zip_entries(l_zip_key).file_name)) =
               lower(file_basename(trim(r.file_name))) then
              l_match_count := l_match_count + 1;
              l_zip_entry := l_zip_key;
            end if;
            l_zip_key := l_zip_entries.next(l_zip_key);
          end loop;

          if l_match_count > 1 then
            l_lookup_error := 'Multiple ZIP entries share the base name "' ||
                              file_basename(trim(r.file_name)) ||
                              '". Put the full archive path in file_name.';
            l_zip_entry := null;
          end if;
        end if;

        if l_zip_entry is not null then
          l_image_blob := apex_zip.get_file_content(
            p_zipped_blob => p_zip_blob,
            p_dir_entry   => l_zip_entries(l_zip_entry)
          );
        end if;

        l_mime_type := mime_from_name(r.file_name);

        if l_mode = 'CONFIGURED' then
          l_demo_profile := null;
        elsif l_mode = 'DEMO_MANIFEST' then
          l_demo_profile := upper(trim(r.demo_profile));
          if l_demo_profile is null then
            l_lookup_error := 'demo_profile is required when Processing mode is Demo - use manifest profile.';
          end if;
        elsif l_mode = 'DEMO_MIXED' then
          l_demo_profile := upper(trim(r.demo_profile));
          if l_demo_profile is null then
            l_demo_profile := case mod(l_row_number - 1, 23)
              when 0 then 'PASS_SPIRITS'
              when 1 then 'PASS_WINE'
              when 2 then 'PASS_BEER'
              when 3 then 'ABV_NOT_APPLICABLE_WINE'
              when 4 then 'ABV_NOT_APPLICABLE_BEER'
              when 5 then 'IMPORT_COUNTRY_MATCH'
              when 6 then 'BRAND_MISMATCH'
              when 7 then 'CLASS_TYPE_MISMATCH'
              when 8 then 'BEVERAGE_TYPE_MISMATCH'
              when 9 then 'ABV_MISMATCH'
              when 10 then 'MISSING_ABV'
              when 11 then 'NET_CONTENTS_MISMATCH'
              when 12 then 'PRODUCER_MISMATCH'
              when 13 then 'IMPORT_COUNTRY_MISMATCH'
              when 14 then 'WARNING_ERROR'
              when 15 then 'MISSING_WARNING'
              when 16 then 'CAPS_ONLY_ERROR'
              when 17 then 'BOLD_ONLY_ERROR'
              when 18 then 'LOW_CONFIDENCE'
              when 19 then 'WARNING_LEGIBILITY_REVIEW'
              when 20 then 'UNREADABLE_IMAGE'
              when 21 then 'TYPOGRAPHY_UNCERTAIN'
              else 'NON_ALCOHOL'
            end;
          end if;
        else
          l_demo_profile := l_mode;
        end if;

        begin
          if l_lookup_error is not null then
            raise_application_error(-20057, l_lookup_error);
          elsif l_zip_entry is null then
            raise_application_error(-20046, 'No image in the ZIP matches manifest file_name "' || trim(r.file_name) || '".');
          end if;

          verify_label(
            p_file_name              => r.file_name,
            p_mime_type              => l_mime_type,
            p_image_blob             => l_image_blob,
            p_application_ref        => r.application_ref,
            p_beverage_type           => l_beverage_type,
            p_abv_required            => l_abv_required,
            p_expected_brand_name    => r.brand_name,
            p_expected_class_type    => r.class_type,
            p_expected_abv           => l_abv,
            p_expected_net_contents  => r.net_contents,
            p_expected_producer      => r.producer,
            p_expected_country       => r.country,
            p_demo_profile           => l_demo_profile,
            p_batch_id               => p_batch_id,
            p_verification_id        => l_verification_id
          );
        exception
          when others then
            l_error_message := substr(sqlerrm, 1, 4000);
            insert_batch_error(
              p_batch_id,
              r.application_ref,
              r.file_name,
              r.beverage_type,
              r.abv_required,
              r.brand_name,
              r.class_type,
              l_abv,
              r.net_contents,
              r.producer,
              r.country,
              l_error_message
            );
        end;

        if l_image_blob is not null and dbms_lob.istemporary(l_image_blob) = 1 then
          dbms_lob.freetemporary(l_image_blob);
        end if;
        l_image_blob := null;
      end loop;

      select count(*),
             sum(case when overall_status = 'PASS' then 1 else 0 end),
             sum(case when overall_status = 'FAIL' then 1 else 0 end),
             sum(case when overall_status = 'REVIEW' then 1 else 0 end)
        into l_processed, l_pass, l_fail, l_review
        from alv_verifications
       where batch_id = p_batch_id;

      l_elapsed_ms := round((dbms_utility.get_time - l_start) * 10);

      update alv_batches
         set status = 'COMPLETED',
             processed_count = coalesce(l_processed, 0),
             pass_count = coalesce(l_pass, 0),
             fail_count = coalesce(l_fail, 0),
             review_count = coalesce(l_review, 0),
             processing_ms = l_elapsed_ms,
             completed_at = systimestamp,
             notes = case
               when l_mode = 'CONFIGURED' and l_provider = 'OPENAI'
                 then 'Processed synchronously with the configured live provider.'
               else 'Processed synchronously in deterministic demo mode using explicit beverage applicability and row-level demo profiles.'
             end
       where id = p_batch_id;
    exception
      when others then
        l_error_message := substr(sqlerrm, 1, 4000);
        if l_image_blob is not null and dbms_lob.istemporary(l_image_blob) = 1 then
          dbms_lob.freetemporary(l_image_blob);
        end if;
        l_image_blob := null;
        l_elapsed_ms := round((dbms_utility.get_time - l_start) * 10);
        select count(*),
               sum(case when overall_status = 'PASS' then 1 else 0 end),
               sum(case when overall_status = 'FAIL' then 1 else 0 end),
               sum(case when overall_status = 'REVIEW' then 1 else 0 end)
          into l_processed, l_pass, l_fail, l_review
          from alv_verifications
         where batch_id = p_batch_id;

        update alv_batches
           set status = 'FAILED',
               processed_count = coalesce(l_processed, 0),
               pass_count = coalesce(l_pass, 0),
               fail_count = coalesce(l_fail, 0),
               review_count = coalesce(l_review, 0),
               processing_ms = l_elapsed_ms,
               completed_at = systimestamp,
               notes = l_error_message
         where id = p_batch_id;

        -- Propagate fatal batch errors so APEX displays an error rather than a
        -- misleading success notification. Row-level problems remain isolated
        -- and are represented as REVIEW records by insert_batch_error.
        raise;
    end;
  end process_batch;
end alv_verification_pkg;
